"""Run the benchmark: Jev operators (planner + Semantic Sheet engine) vs. a one-shot gpt-6-astra answer.

    python benchmarks/run.py                                   # all scenarios, both arms, default planner (gpt-6-astra via OpenAI)
    python benchmarks/run.py -s support_requests               # one scenario
    python benchmarks/run.py --reuse oneshot                   # re-run the operators and comparison, reuse stored one-shot answers
    python benchmarks/run.py --planner-provider openrouter --planner-model z-ai/glm-5.3-flash --reuse oneshot

Each planner configuration is a separate *run* (default name planner-<model>); results go to
benchmarks/results/<run>/<scenario>.json and the operators' raw outputs to data/benchmark/raw_outputs/<run>/.
One-shot answers do not depend on the planner and are shared across runs (data/benchmark/raw_outputs/<scenario>/oneshot.json).

Environment: OPENAI_API_KEY (one-shot arm and the OpenAI planner), OPENROUTER_API_KEY (OpenRouter planner),
TYPESAFE_API_KEY (Jev). Datasets: run scripts/prepare_samples.py first. RESULTS.md is regenerated by report.py."""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from common import BENCH_DATA_DIR, RESULTS_DIR, ROOT, dump_json  # noqa: E402

RAW_DIR = BENCH_DATA_DIR / "raw_outputs"


def parse_args() -> argparse.Namespace:
    ap = argparse.ArgumentParser()
    ap.add_argument("-s", "--scenarios", default="", help="comma-separated scenario keys (default: all)")
    ap.add_argument("--arms", default="pipeline,oneshot", help="which arms to run: pipeline, oneshot")
    ap.add_argument("--reuse", default="", help="reuse stored raw outputs instead of calling providers: pipeline, oneshot")
    ap.add_argument("--oneshot-workers", type=int, default=6)
    ap.add_argument("--planner-provider", default=os.environ.get("PLANNER_PROVIDER", "openai"), choices=["openai", "openrouter"])
    ap.add_argument("--planner-model", default=os.environ.get("PLANNER_MODEL", "gpt-6-astra"))
    ap.add_argument("--planner-reasoning", default=os.environ.get("PLANNER_REASONING", "high"))
    ap.add_argument("--run", default="", help="run name (default: planner-<model>)")
    return ap.parse_args()


def run_name_for(model: str) -> str:
    return "planner-" + re.sub(r"[^a-z0-9.]+", "-", model.split("/")[-1].lower()).strip("-")


def main() -> int:
    args = parse_args()
    run = args.run or run_name_for(args.planner_model)
    # The engine reads its configuration at import time, so set it before importing the pipeline driver.
    os.environ["PLANNER_PROVIDER"] = args.planner_provider
    os.environ["PLANNER_MODEL"] = args.planner_model
    os.environ["PLANNER_REASONING"] = args.planner_reasoning
    os.environ.setdefault("SEMSHEET_DATA_DIR", str(ROOT / "data" / "benchmark_store"))
    os.environ.setdefault("SEMSHEET_WORKSPACE_BUDGET_USD", "50")

    import pandas as pd

    from oneshot import OneShotResult, run_oneshot
    from pipeline import PipelineResult, run_pipeline
    from scenarios import SCENARIOS, Prepared

    results_dir = RESULTS_DIR / run
    raw_run_dir = RAW_DIR / run

    def save_pipeline(key: str, pr: PipelineResult) -> None:
        d = raw_run_dir / key / "pipeline"
        d.mkdir(parents=True, exist_ok=True)
        for sid, df in pr.steps.items():
            df.to_parquet(d / f"step__{sid}.parquet", index=False)
        for name, ds in pr.datasets.items():
            ds["frame"].to_parquet(d / f"dataset__{name}.parquet", index=False)
        meta = pr.summary()
        meta["dataset_row_id_maps"] = {k: v["row_id_map"] for k, v in pr.datasets.items()}
        dump_json(d / "meta.json", meta)

    def load_pipeline(key: str) -> PipelineResult | None:
        d = raw_run_dir / key / "pipeline"
        if not (d / "meta.json").exists():
            return None
        meta = json.loads((d / "meta.json").read_text(encoding="utf-8"))
        pr = PipelineResult(plan=meta["plan"], planner=meta["planner"], estimate=meta["estimate"], job=meta["job"], timings=meta["timings_seconds"], cost=meta["cost"], error=meta["error"])
        for p in d.glob("step__*.parquet"):
            pr.steps[p.stem[len("step__"):]] = pd.read_parquet(p)
        for p in d.glob("dataset__*.parquet"):
            name = p.stem[len("dataset__"):]
            pr.datasets[name] = {**meta["datasets"].get(name, {}), "frame": pd.read_parquet(p), "row_id_map": {int(k): int(v) for k, v in meta["dataset_row_id_maps"].get(name, {}).items()}}
        return pr

    def save_oneshot(key: str, r: OneShotResult) -> None:
        dump_json(RAW_DIR / key / "oneshot.json", {**r.summary(), "output": r.output})

    def load_oneshot(key: str) -> OneShotResult | None:
        p = RAW_DIR / key / "oneshot.json"
        if not p.exists():
            return None
        d = json.loads(p.read_text(encoding="utf-8"))
        d.pop("output_summary", None)
        return OneShotResult(**{k: v for k, v in d.items() if k in OneShotResult.__dataclass_fields__})

    keys = [k for k in args.scenarios.split(",") if k] or list(SCENARIOS)
    arms = set(args.arms.split(","))
    reuse = set(args.reuse.split(","))
    unknown = [k for k in keys if k not in SCENARIOS]
    if unknown:
        print(f"unknown scenarios: {unknown}; known: {list(SCENARIOS)}", file=sys.stderr)
        return 2
    if "oneshot" in arms and "oneshot" not in reuse and not os.environ.get("OPENAI_API_KEY"):
        print("OPENAI_API_KEY is required for the one-shot arm", file=sys.stderr)
        return 2
    if "pipeline" in arms and "pipeline" not in reuse:
        if not os.environ.get("TYPESAFE_API_KEY"):
            print("TYPESAFE_API_KEY is required for the operators arm", file=sys.stderr)
            return 2
        key_var = "OPENROUTER_API_KEY" if args.planner_provider == "openrouter" else "OPENAI_API_KEY"
        if not os.environ.get(key_var):
            print(f"{key_var} is required for the {args.planner_provider} planner", file=sys.stderr)
            return 2
    print(f"run={run} planner={args.planner_provider}/{args.planner_model} ({args.planner_reasoning}) -> {results_dir.relative_to(ROOT)}")

    prepared: dict[str, Prepared] = {}
    for k in keys:
        prepared[k] = SCENARIOS[k].prepare()
        for t in prepared[k].tables:
            print(f"[{k}] table {t.name}: {t.row_count} rows, ~{t.est_tokens:,} tokens -> {t.path.relative_to(ROOT)}")

    # One-shot calls are long network waits; start them all first, then run the pipelines sequentially.
    oneshots: dict[str, OneShotResult] = {}
    futures = {}
    pool = ThreadPoolExecutor(max_workers=max(1, args.oneshot_workers))
    if "oneshot" in arms:
        for k in keys:
            cached = load_oneshot(k) if "oneshot" in reuse else None
            if cached is not None:
                oneshots[k] = cached
                print(f"[{k}] one-shot: reusing stored answer ({cached.status})")
            else:
                print(f"[{k}] one-shot: submitting to gpt-6-astra (high)")
                futures[k] = pool.submit(run_oneshot, SCENARIOS[k], prepared[k])

    pipelines: dict[str, PipelineResult] = {}
    if "pipeline" in arms:
        for k in keys:
            cached = load_pipeline(k) if "pipeline" in reuse else None
            if cached is not None:
                pipelines[k] = cached
                print(f"[{k}] pipeline: reusing stored run")
                continue
            print(f"[{k}] pipeline: import -> plan -> Jev job")
            t0 = time.time()
            pr = run_pipeline(SCENARIOS[k], prepared[k])
            pipelines[k] = pr
            save_pipeline(k, pr)
            print(f"[{k}] pipeline done in {time.time() - t0:.0f}s: job={pr.job.get('state')} cost={pr.cost.get('total_usd')} error={pr.error}")

    for k, f in futures.items():
        r = f.result()
        oneshots[k] = r
        save_oneshot(k, r)
        print(f"[{k}] one-shot done: status={r.status} latency={r.latency_seconds}s cost={r.cost.get('usd')} error={r.error}")
    pool.shutdown(wait=True)

    for k in keys:
        sc = SCENARIOS[k]
        pr = pipelines.get(k) or load_pipeline(k) or PipelineResult(error="pipeline arm not run")
        os_ = oneshots.get(k) or load_oneshot(k) or OneShotResult(error="one-shot arm not run")
        try:
            comparison = sc.compare(prepared[k], pr, os_)
        except Exception as e:  # noqa: BLE001
            comparison = {"error": f"comparison failed: {type(e).__name__}: {e}"}
        result = {
            "run": run, "planner_config": {"provider": args.planner_provider, "model": args.planner_model, "reasoning_effort": args.planner_reasoning},
            "scenario": k, "title": sc.title, "prompt": sc.prompt,
            "inputs": [{"name": t.name, "rows": t.row_count, "columns": t.columns, "approx_tokens": t.est_tokens} for t in prepared[k].tables],
            "notes": prepared[k].notes,
            "pipeline": pr.summary(), "oneshot": os_.summary(), "comparison": comparison,
            "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        }
        dump_json(results_dir / f"{k}.json", result)
        print(f"[{k}] wrote {results_dir / f'{k}.json'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
